-- Run once in the provincial Supabase project's SQL Editor.
-- Adds email support to prov_coordinators and sets up Google sign-up approval workflow.
begin;

-- 1. Add email column to prov_coordinators if not exists
alter table public.prov_coordinators
  add column if not exists email text;

-- 2. Backfill email from auth.users for existing coordinators
update public.prov_coordinators c
set email = u.email
from auth.users u
where c.auth_user_id = u.id
  and (c.email is null or c.email = '');

-- 3. Grant select on email column to authenticated users
grant select (id, username, fullname, email, is_admin, auth_user_id, must_change_password)
  on public.prov_coordinators to authenticated;

-- 4. Create table for pending coordinator requests / Google sign-ups
create table if not exists public.prov_coordinator_requests (
  id integer generated by default as identity primary key,
  auth_user_id uuid unique not null references auth.users(id) on delete cascade,
  email text not null,
  fullname text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by text
);

alter table public.prov_coordinator_requests enable row level security;

-- Policies for prov_coordinator_requests
drop policy if exists prov_coord_requests_insert_own on public.prov_coordinator_requests;
create policy prov_coord_requests_insert_own on public.prov_coordinator_requests
  for insert to authenticated
  with check (auth_user_id = (select auth.uid()));

drop policy if exists prov_coord_requests_update_own on public.prov_coordinator_requests;
create policy prov_coord_requests_update_own on public.prov_coordinator_requests
  for update to authenticated
  using (auth_user_id = (select auth.uid()));

drop policy if exists prov_coord_requests_select on public.prov_coordinator_requests;
create policy prov_coord_requests_select on public.prov_coordinator_requests
  for select to authenticated
  using (auth_user_id = (select auth.uid()) or (select private.prov_is_admin()));

drop policy if exists prov_coord_requests_admin_modify on public.prov_coordinator_requests;
create policy prov_coord_requests_admin_modify on public.prov_coordinator_requests
  for all to authenticated
  using ((select private.prov_is_admin()))
  with check ((select private.prov_is_admin()));

grant select, insert, update, delete on public.prov_coordinator_requests to authenticated;
grant usage, select on sequence public.prov_coordinator_requests_id_seq to authenticated;

-- 5. Stored function to approve a coordinator request atomically
create or replace function public.prov_approve_coordinator_request(
  p_request_id integer,
  p_is_admin boolean default false
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_req record;
  v_base_username text;
  v_username text;
  v_counter integer := 1;
  v_coord_id integer;
begin
  if not private.prov_is_admin() then
    raise exception 'Only an administrator may approve coordinator requests';
  end if;

  select * into v_req
  from public.prov_coordinator_requests
  where id = p_request_id and status = 'pending';

  if not found then
    raise exception 'Pending request not found';
  end if;

  -- Check if already a coordinator
  if exists (select 1 from public.prov_coordinators where auth_user_id = v_req.auth_user_id) then
    update public.prov_coordinator_requests
    set status = 'approved',
        reviewed_at = now(),
        reviewed_by = (select fullname from public.prov_coordinators where auth_user_id = (select auth.uid()))
    where id = p_request_id;
    return jsonb_build_object('ok', true, 'message', 'User is already an approved coordinator');
  end if;

  -- Derive clean username from email
  v_base_username := lower(regexp_replace(split_part(v_req.email, '@', 1), '[^a-z0-9._-]', '', 'g'));
  if length(v_base_username) < 3 then
    v_base_username := 'coord_' || v_base_username;
  end if;
  v_username := v_base_username;

  -- Ensure unique username
  while exists (select 1 from public.prov_coordinators where lower(username) = lower(v_username)) loop
    v_counter := v_counter + 1;
    v_username := v_base_username || v_counter::text;
  end loop;

  -- Insert into prov_coordinators
  insert into public.prov_coordinators (
    username,
    fullname,
    email,
    is_admin,
    auth_user_id,
    passwordhash,
    must_change_password
  ) values (
    v_username,
    v_req.fullname,
    v_req.email,
    coalesce(p_is_admin, false),
    v_req.auth_user_id,
    '',
    false
  ) returning id into v_coord_id;

  -- Update request status
  update public.prov_coordinator_requests
  set status = 'approved',
      reviewed_at = now(),
      reviewed_by = (select fullname from public.prov_coordinators where auth_user_id = (select auth.uid()))
  where id = p_request_id;

  return jsonb_build_object(
    'ok', true,
    'coordinator_id', v_coord_id,
    'username', v_username,
    'fullname', v_req.fullname,
    'email', v_req.email
  );
end;
$$;

-- 6. Stored function to reject a coordinator request
create or replace function public.prov_reject_coordinator_request(
  p_request_id integer
)
returns jsonb language plpgsql security definer set search_path = '' as $$
begin
  if not private.prov_is_admin() then
    raise exception 'Only an administrator may reject coordinator requests';
  end if;

  update public.prov_coordinator_requests
  set status = 'rejected',
      reviewed_at = now(),
      reviewed_by = (select fullname from public.prov_coordinators where auth_user_id = (select auth.uid()))
  where id = p_request_id;

  return jsonb_build_object('ok', true);
end;
$$;

revoke all on function public.prov_approve_coordinator_request(integer, boolean) from public;
revoke all on function public.prov_reject_coordinator_request(integer) from public;
grant execute on function public.prov_approve_coordinator_request(integer, boolean) to authenticated;
grant execute on function public.prov_reject_coordinator_request(integer) to authenticated;

-- 7. Stored function for administrator to update coordinator details directly (Full Name, Username, Email, Admin Access)
create or replace function public.prov_admin_update_coordinator(
  p_id integer,
  p_fullname text,
  p_username text,
  p_email text,
  p_is_admin boolean
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_caller_id integer;
  v_cleaned_username text;
begin
  if not private.prov_is_admin() then
    raise exception 'Only an administrator may update coordinators';
  end if;

  select id into v_caller_id from public.prov_coordinators where auth_user_id = (select auth.uid());
  if v_caller_id = p_id and p_is_admin is distinct from true then
    raise exception 'You cannot remove your own administrator access';
  end if;

  v_cleaned_username := lower(btrim(p_username));
  if not (v_cleaned_username ~ '^[a-z0-9._-]+$') then
    raise exception 'Username must contain only lowercase letters, numbers, dots, underscores, or hyphens';
  end if;

  if exists (select 1 from public.prov_coordinators where lower(username) = v_cleaned_username and id <> p_id) then
    raise exception 'Username "%" is already taken by another coordinator', v_cleaned_username;
  end if;

  update public.prov_coordinators
  set fullname = btrim(p_fullname),
      username = v_cleaned_username,
      email = nullif(btrim(p_email), ''),
      is_admin = coalesce(p_is_admin, false)
  where id = p_id;

  return jsonb_build_object('ok', true);
end;
$$;

-- 8. Stored function for administrator to delete a coordinator account
create or replace function public.prov_admin_delete_coordinator(
  p_id integer
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_caller_id integer;
  v_auth_user_id uuid;
begin
  if not private.prov_is_admin() then
    raise exception 'Only an administrator may delete coordinators';
  end if;

  select id into v_caller_id from public.prov_coordinators where auth_user_id = (select auth.uid());
  if v_caller_id = p_id then
    raise exception 'You cannot delete your own account';
  end if;

  select auth_user_id into v_auth_user_id from public.prov_coordinators where id = p_id;

  -- Delete coordinator profile (events with this coordinator set coordinatorid to null automatically)
  delete from public.prov_coordinators where id = p_id;

  -- Clean up associated request record if one exists
  if v_auth_user_id is not null then
    delete from public.prov_coordinator_requests where auth_user_id = v_auth_user_id;
  end if;

  return jsonb_build_object('ok', true);
end;
$$;

revoke all on function public.prov_admin_update_coordinator(integer, text, text, text, boolean) from public;
revoke all on function public.prov_admin_delete_coordinator(integer) from public;
grant execute on function public.prov_admin_update_coordinator(integer, text, text, text, boolean) to authenticated;
grant execute on function public.prov_admin_delete_coordinator(integer) to authenticated;

-- 9. Direct table policies for administrators
drop policy if exists prov_coordinators_admin_update on public.prov_coordinators;
create policy prov_coordinators_admin_update on public.prov_coordinators
  for update to authenticated
  using ((select private.prov_is_admin()))
  with check ((select private.prov_is_admin()));

drop policy if exists prov_coordinators_admin_delete on public.prov_coordinators;
create policy prov_coordinators_admin_delete on public.prov_coordinators
  for delete to authenticated
  using ((select private.prov_is_admin()));

grant update (fullname, username, email, is_admin) on public.prov_coordinators to authenticated;
grant delete on public.prov_coordinators to authenticated;

commit;
