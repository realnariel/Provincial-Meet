-- Run ONCE in the NEW provincial Supabase project, after schema.sql.
-- Existing provincial results are copied into prov_event_awards. This script
-- never reads or writes congressional tables. Review before running.
begin;

do $$
begin
  if to_regclass('public.prov_events') is null or
     to_regclass('public.prov_teams') is null or
     to_regprocedure('private.prov_can_manage_event(integer)') is null then
    raise exception 'Provincial schema is incomplete; apply schema.sql first';
  end if;
  if to_regclass('public.cong_events') is not null then
    raise exception 'Refusing to run in a congressional database';
  end if;
end $$;

create table if not exists public.prov_event_awards (
  id bigint generated by default as identity primary key,
  event_id integer not null references public.prov_events(id) on delete cascade,
  medal text not null check (medal in ('Gold', 'Silver', 'Bronze')),
  team_id integer not null references public.prov_teams(id),
  winner_names text,
  sort_order integer not null check (sort_order >= 0),
  unique (event_id, medal, sort_order)
);
create index if not exists prov_event_awards_team_idx on public.prov_event_awards(team_id);

-- Preserve already-published provincial awards before replacing the tally.
insert into public.prov_event_awards (event_id, medal, team_id, winner_names, sort_order)
select id, 'Gold', goldteamid, gold_winner_name, 0 from public.prov_events where goldteamid is not null
union all
select id, 'Silver', silverteamid, silver_winner_name, 0 from public.prov_events where silverteamid is not null
union all
select id, 'Bronze', bronzeteamid, bronze_winner_name, 0 from public.prov_events where bronzeteamid is not null
on conflict (event_id, medal, sort_order) do nothing;

-- A team may win different medals through different athletes in one event.
alter table public.prov_events drop constraint if exists prov_events_distinct_medal_teams;

alter table public.prov_event_awards enable row level security;
revoke all on public.prov_event_awards from anon, authenticated;
grant select on public.prov_event_awards to anon, authenticated;
drop policy if exists prov_event_awards_public_read on public.prov_event_awards;
create policy prov_event_awards_public_read on public.prov_event_awards
  for select to anon, authenticated using (true);

create or replace view public.prov_medal_tallies
with (security_invoker = true) as
select t.id as teamid, d.division,
  count(a.id) filter (where a.medal = 'Gold')::integer as gold,
  count(a.id) filter (where a.medal = 'Silver')::integer as silver,
  count(a.id) filter (where a.medal = 'Bronze')::integer as bronze
from public.prov_teams t
cross join (values ('Elementary'::text), ('Secondary'::text), ('Paragames'::text)) d(division)
left join (
  select a.id, a.medal, a.team_id, e.division
  from public.prov_event_awards a
  join public.prov_events e on e.id = a.event_id and e.status = 'Completed'
) a on a.team_id = t.id and a.division = d.division
group by t.id, d.division;

-- One call atomically replaces all medal rows for the event. The old single-
-- medal columns remain synchronized with the first award for compatibility.
create or replace function public.prov_publish_awards(p_event_id integer, p_awards jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_title text;
  v_award record;
  v_name text;
  v_gender text;
begin
  if not private.prov_can_manage_event(p_event_id) then
    raise exception 'Not permitted to publish this event';
  end if;
  if jsonb_typeof(p_awards) is distinct from 'array' or jsonb_array_length(p_awards) > 100 then
    raise exception 'Awards must be an array of at most 100 entries';
  end if;
  if jsonb_array_length(p_awards) = 0 then
    raise exception 'At least one award is required to publish a result';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_awards) as item(x)
    where jsonb_typeof(x) is distinct from 'object'
       or (x->>'medal') is null
       or x->>'medal' not in ('Gold', 'Silver', 'Bronze')
       or (x->>'team_id') is null
       or (x->>'team_id') !~ '^[0-9]+$'
  ) then
    raise exception 'Each award needs a valid medal and team';
  end if;

  select title into v_title from public.prov_events where id = p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if exists (
    select 1 from jsonb_array_elements(p_awards) as item(x)
    left join public.prov_teams t on t.id = (x->>'team_id')::integer
    where t.id is null
  ) then
    raise exception 'Unknown award team';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_awards) as item(x)
    group by x->>'medal', x->>'team_id', lower(btrim(coalesce(x->>'winner_names', '')))
    having count(*) > 1
  ) then
    raise exception 'Duplicate team and athlete names for one medal';
  end if;

  delete from public.prov_event_awards where event_id = p_event_id;
  insert into public.prov_event_awards(event_id, medal, team_id, winner_names, sort_order)
  select p_event_id, x->>'medal', (x->>'team_id')::integer,
    nullif(btrim(x->>'winner_names'), ''),
    (row_number() over (partition by x->>'medal' order by ordinality) - 1)::integer
  from jsonb_array_elements(p_awards) with ordinality as item(x, ordinality);

  update public.prov_events set
    goldteamid = (select team_id from public.prov_event_awards where event_id = p_event_id and medal = 'Gold' order by sort_order limit 1),
    silverteamid = (select team_id from public.prov_event_awards where event_id = p_event_id and medal = 'Silver' order by sort_order limit 1),
    bronzeteamid = (select team_id from public.prov_event_awards where event_id = p_event_id and medal = 'Bronze' order by sort_order limit 1),
    gold_winner_name = (select winner_names from public.prov_event_awards where event_id = p_event_id and medal = 'Gold' order by sort_order limit 1),
    silver_winner_name = (select winner_names from public.prov_event_awards where event_id = p_event_id and medal = 'Silver' order by sort_order limit 1),
    bronze_winner_name = (select winner_names from public.prov_event_awards where event_id = p_event_id and medal = 'Bronze' order by sort_order limit 1),
    status = 'Completed'
  where id = p_event_id;

  v_gender := case when v_title ilike '%boys%' then 'M'
                   when v_title ilike '%girls%' then 'W' else null end;
  for v_award in
    select a.winner_names, t.name as team_name from public.prov_event_awards a
    join public.prov_teams t on t.id = a.team_id
    where a.event_id = p_event_id and a.medal = 'Gold'
  loop
    for v_name in
      select initcap(btrim(value)) from regexp_split_to_table(
        coalesce(v_award.winner_names, ''), E'[\r\n]+'
      ) as names(value) where btrim(value) <> ''
    loop
      update public.prov_qualifiers set participant_name = v_name,
        team = v_award.team_name, role = 'Athlete', gender = v_gender,
        updated_by = auth.uid(), updated_at = now() at time zone 'utc'
      where event_id = p_event_id and lower(participant_name) = lower(v_name);
      if not found then
        insert into public.prov_qualifiers(event_id, participant_name, team, role, gender, updated_by)
        values (p_event_id, v_name, v_award.team_name, 'Athlete', v_gender, auth.uid());
      end if;
    end loop;
  end loop;
end;
$$;

create or replace function public.prov_clear_result(p_event_id integer)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not private.prov_can_manage_event(p_event_id) then
    raise exception 'Not permitted to clear this event';
  end if;
  delete from public.prov_event_awards where event_id = p_event_id;
  update public.prov_events set status = 'Pending', goldteamid = null,
    silverteamid = null, bronzeteamid = null, gold_winner_name = null,
    silver_winner_name = null, bronze_winner_name = null where id = p_event_id;
  delete from public.prov_qualifiers where event_id = p_event_id;
end;
$$;

revoke all on function public.prov_publish_awards(integer, jsonb) from public;
grant execute on function public.prov_publish_awards(integer, jsonb) to authenticated;
revoke all on function public.prov_publish_result(integer, integer, integer, integer, text, text, text) from authenticated;
revoke all on function public.prov_clear_result(integer) from public;
grant execute on function public.prov_clear_result(integer) to authenticated;
grant select on public.prov_medal_tallies to anon, authenticated;

-- Result columns can only be changed through the atomic award RPC.
revoke update on public.prov_events from authenticated;
grant update (title, sport_name, sport_category, event_category, division,
  coordinatorid, status) on public.prov_events to authenticated;

commit;

-- Verify after applying: copied awards, all three divisions, no lost events.
select count(*) as awards from public.prov_event_awards;
select count(*) as events from public.prov_events;
