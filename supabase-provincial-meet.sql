-- Bohol Provincial Athletic Meet 2026
-- Safe to run beside the old congressional database objects.
-- This script creates only prov_* objects and never drops or changes cong_* / subcong_* data.

begin;

create table if not exists public.prov_teams (
    id integer generated by default as identity primary key,
    name text not null,
    acronym text not null,
    created_at timestamptz not null default now(),
    constraint prov_teams_name_not_blank check (btrim(name) <> ''),
    constraint prov_teams_acronym_not_blank check (btrim(acronym) <> '')
);

create unique index if not exists prov_teams_name_unique_ci
    on public.prov_teams (lower(btrim(name)));
create unique index if not exists prov_teams_acronym_unique_ci
    on public.prov_teams (lower(btrim(acronym)));

-- Provincial delegations are registered once. Divisions are assigned by events,
-- so these rows must not be duplicated for Elementary, Secondary, or Paragames.
insert into public.prov_teams (name, acronym)
select seed.name, seed.acronym
from (values
    ('1st Congressional District', 'CD 1'),
    ('2nd Congressional District', 'CD 2'),
    ('3rd Congressional District', 'CD 3'),
    ('Bohol Association of Catholic Schools - Diocese of Tagbilaran', 'BACS-Tagbilaran'),
    ('Bohol Association of Catholic Schools - Diocese of Talibon', 'BACS-Talibon'),
    ('Bohol Institute of Technology - International College', 'BIT-IC')
) as seed(name, acronym)
where not exists (
    select 1
    from public.prov_teams existing
    where lower(btrim(existing.name)) = lower(btrim(seed.name))
       or lower(btrim(existing.acronym)) = lower(btrim(seed.acronym))
);

create table if not exists public.prov_coordinators (
    id integer generated by default as identity primary key,
    username varchar(50) not null,
    passwordhash varchar(100) not null,
    fullname varchar(100) not null,
    is_admin boolean not null default false,
    created_at timestamptz not null default now(),
    constraint prov_coordinators_username_not_blank check (btrim(username) <> ''),
    constraint prov_coordinators_fullname_not_blank check (btrim(fullname) <> '')
);

create unique index if not exists prov_coordinators_username_unique_ci
    on public.prov_coordinators (lower(btrim(username)));

create table if not exists public.prov_events (
    id integer generated by default as identity primary key,
    title text not null,
    sport_name text,
    sport_category text,
    event_category text,
    division text not null,
    status text not null default 'Pending',
    coordinatorid integer references public.prov_coordinators(id) on delete set null,
    goldteamid integer references public.prov_teams(id) on delete set null,
    silverteamid integer references public.prov_teams(id) on delete set null,
    bronzeteamid integer references public.prov_teams(id) on delete set null,
    createdat timestamp without time zone not null default (now() at time zone 'utc'),
    updatedat timestamp without time zone default (now() at time zone 'utc'),
    gold_winner_name text,
    silver_winner_name text,
    bronze_winner_name text,
    last_updated_by text,
    constraint prov_events_title_not_blank check (btrim(title) <> ''),
    constraint prov_events_division_check check (division in ('Elementary', 'Secondary', 'Paragames')),
    constraint prov_events_status_check check (status in ('Pending', 'Completed')),
    constraint prov_events_distinct_medal_teams check (
        (goldteamid is null or silverteamid is null or goldteamid <> silverteamid) and
        (goldteamid is null or bronzeteamid is null or goldteamid <> bronzeteamid) and
        (silverteamid is null or bronzeteamid is null or silverteamid <> bronzeteamid)
    )
);

-- Remove obsolete columns if an earlier draft of the provincial schema was run.
-- This targets prov_events only and never alters the congressional tables.
alter table public.prov_events
    drop column if exists source_cong_event_id,
    drop column if exists eliminationtype,
    drop column if exists teamaid,
    drop column if exists teambid,
    drop column if exists school_gold,
    drop column if exists school_silver,
    drop column if exists school_bronze;

-- Earlier drafts constrained event_category to a short list. The source
-- catalog can contain other labels, which should be preserved on import.
alter table public.prov_events
    drop constraint if exists prov_events_category_check;

create index if not exists prov_events_division_sport_idx
    on public.prov_events (division, sport_name, title);
create index if not exists prov_events_coordinator_idx
    on public.prov_events (coordinatorid);
create index if not exists prov_events_updated_idx
    on public.prov_events (updatedat desc);

-- Copy the congressional event catalog without copying results, coordinators,
-- winners, or completion state. The legacy congressional table stores gender
-- category in sport_category and event type in event_category; the provincial
-- schema normalizes those two values into their correctly named columns.
-- Skip catalog entries already present, even if their result status changed.
insert into public.prov_events (
    title,
    sport_name,
    sport_category,
    division,
    event_category,
    status,
    updatedat
)
select
    source.title,
    source.sport_name,
    source.event_category,
    source.division,
    source.sport_category,
    'Pending',
    (now() at time zone 'utc')
from public.cong_events source
where not exists (
    select 1
    from public.prov_events target
    where target.title = source.title
      and target.sport_name is not distinct from source.sport_name
      and target.sport_category is not distinct from source.event_category
      and target.division = source.division
      and target.event_category is not distinct from source.sport_category
);

create table if not exists public.prov_qualifiers (
    id uuid primary key default gen_random_uuid(),
    event_id integer not null references public.prov_events(id) on delete cascade,
    participant_name text not null,
    role text default 'Athlete',
    team text,
    specific_district text,
    school text,
    gender text,
    tshirt_size text,
    updated_by uuid,
    updated_at timestamp without time zone not null default (now() at time zone 'utc'),
    constraint prov_qualifiers_name_not_blank check (btrim(participant_name) <> '')
);

create index if not exists prov_qualifiers_event_idx on public.prov_qualifiers (event_id);
create index if not exists prov_qualifiers_team_idx on public.prov_qualifiers (team);

create table if not exists public.prov_cron_execution_logs (
    id bigint generated by default as identity primary key,
    executed_at timestamp without time zone not null default (now() at time zone 'utc'),
    task_name text not null,
    status text not null,
    status_code integer not null,
    execution_time_ms double precision not null,
    details text,
    caller_ip text,
    user_agent text
);

create index if not exists prov_cron_logs_executed_idx
    on public.prov_cron_execution_logs (executed_at desc);

-- Live medal standings. Each team is listed once in prov_teams; division is derived
-- automatically from the event that awarded the medal.
create or replace view public.prov_medal_tallies as
select
    t.id as teamid,
    d.division,
    count(e.id) filter (where e.goldteamid = t.id)::integer as gold,
    count(e.id) filter (where e.silverteamid = t.id)::integer as silver,
    count(e.id) filter (where e.bronzeteamid = t.id)::integer as bronze
from public.prov_teams t
cross join (values ('Elementary'::text), ('Secondary'::text), ('Paragames'::text)) d(division)
left join public.prov_events e
    on e.status = 'Completed'
   and e.division = d.division
   and t.id in (e.goldteamid, e.silverteamid, e.bronzeteamid)
group by t.id, d.division;

-- Initial administrator. On first login use username "admin" and password
-- "coordinator"; the application immediately requires a password change.
insert into public.prov_coordinators (username, passwordhash, fullname, is_admin)
select 'admin', 'coordinator', 'Provincial Meet Administrator', true
where not exists (
    select 1 from public.prov_coordinators where lower(btrim(username)) = 'admin'
);

commit;

