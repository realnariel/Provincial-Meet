create table if not exists public.prov_coordinators (
  id integer generated by default as identity primary key,
  username varchar(50) not null check (username ~ '^[a-z0-9._-]+$'),
  passwordhash varchar(100) not null default '', -- legacy column; React never reads or writes it
  fullname varchar(100) not null check (btrim(fullname) <> ''),
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  must_change_password boolean not null default true
);
create unique index if not exists prov_coordinators_username_unique_ci
  on public.prov_coordinators (lower(btrim(username)));

create table if not exists public.prov_events (
  id integer generated by default as identity primary key,
  title text not null check (btrim(title) <> ''),
  sport_name text,
  sport_category text,
  event_category text,
  division text not null check (division in ('Elementary', 'Secondary', 'Paragames')),
  status text not null default 'Pending' check (status in ('Pending', 'Completed')),
  coordinatorid integer references public.prov_coordinators(id) on delete set null,
  goldteamid integer references public.prov_teams(id) on delete set null,
  silverteamid integer references public.prov_teams(id) on delete set null,
  bronzeteamid integer references public.prov_teams(id) on delete set null,
  createdat timestamp without time zone not null default (now() at time zone 'utc'),
  updatedat timestamp without time zone default (now() at time zone 'utc'),
  gold_winner_name text,
  silver_winner_name text,
  bronze_winner_name text,
  last_updated_by text,
  constraint prov_events_distinct_medal_teams check (
    (goldteamid is null or silverteamid is null or goldteamid <> silverteamid) and
    (goldteamid is null or bronzeteamid is null or goldteamid <> bronzeteamid) and
    (silverteamid is null or bronzeteamid is null or silverteamid <> bronzeteamid)
  )
);
create index if not exists prov_events_division_sport_idx on public.prov_events (division, sport_name, title);
create index if not exists prov_events_coordinator_idx on public.prov_events (coordinatorid);
create index if not exists prov_events_updated_idx on public.prov_events (updatedat desc);

create table if not exists public.prov_qualifiers (
  id uuid primary key default gen_random_uuid(),
  event_id integer not null references public.prov_events(id) on delete cascade,
  participant_name text not null check (btrim(participant_name) <> ''),
  role text default 'Athlete',
  team text,
  specific_district text,
  school text,
  gender text,
  tshirt_size text,
  updated_by uuid,
  updated_at timestamp without time zone not null default (now() at time zone 'utc')
);
create index if not exists prov_qualifiers_event_idx on public.prov_qualifiers (event_id);
create index if not exists prov_qualifiers_team_idx on public.prov_qualifiers (team);

-- Kept for table-name compatibility. The static app does not require a cron job.
create table if not exists public.prov_cron_execution_logs (
  id bigint generated by default as identity primary key,
  executed_at timestamp without time zone not null default (now() at time zone 'utc'),
  task_name text not null,
  status text not null,
  status_code integer not null,
  execution_time_ms double precision not null,
  details text,
  caller_ip text,
  user_agent text
);

create or replace view public.prov_medal_tallies
with (security_invoker = true) as
select t.id as teamid, d.division,
  count(e.id) filter (where e.goldteamid = t.id)::integer as gold,
  count(e.id) filter (where e.silverteamid = t.id)::integer as silver,
  count(e.id) filter (where e.bronzeteamid = t.id)::integer as bronze
from public.prov_teams t
cross join (values ('Elementary'::text), ('Secondary'::text), ('Paragames'::text)) d(division)
left join public.prov_events e on e.status = 'Completed'
  and e.division = d.division
  and t.id in (e.goldteamid, e.silverteamid, e.bronzeteamid)
group by t.id, d.division;

-- Policy helpers live outside the exposed public API schema.
create or replace function private.prov_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.prov_coordinators c
    where c.auth_user_id = (select auth.uid())
      and c.is_admin and not c.must_change_password
  );
$$;
create or replace function private.prov_can_manage_event(p_event_id integer)
returns boolean language sql stable security definer set search_path = '' as $$
  select private.prov_is_admin() or exists (
    select 1 from public.prov_events e
    join public.prov_coordinators c on c.id = e.coordinatorid
    where e.id = p_event_id and c.auth_user_id = (select auth.uid())
      and not c.must_change_password
  );
$$;
revoke all on function private.prov_is_admin() from public;
revoke all on function private.prov_can_manage_event(integer) from public;
grant usage on schema private to authenticated;
grant execute on function private.prov_is_admin() to authenticated;
grant execute on function private.prov_can_manage_event(integer) to authenticated;

-- A coordinator may edit only result fields on an assigned event; admins may
-- also edit catalog fields and assignments. The trigger enforces this even
-- when a caller bypasses the React form and sends a direct REST request.
create or replace function private.prov_guard_event_update()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not private.prov_is_admin() and (
    new.title is distinct from old.title or
    new.sport_name is distinct from old.sport_name or
    new.sport_category is distinct from old.sport_category or
    new.event_category is distinct from old.event_category or
    new.division is distinct from old.division or
    new.coordinatorid is distinct from old.coordinatorid or
    new.createdat is distinct from old.createdat
  ) then
    raise exception 'Only an administrator may edit event details or assignments';
  end if;
  new.last_updated_by := (
    select c.fullname from public.prov_coordinators c
    where c.auth_user_id = (select auth.uid())
  );
  new.updatedat := now() at time zone 'utc';
  return new;
end;
$$;
drop trigger if exists prov_guard_event_update on public.prov_events;
create trigger prov_guard_event_update before update on public.prov_events
for each row execute function private.prov_guard_event_update();

